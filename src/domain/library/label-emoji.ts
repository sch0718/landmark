/** 이름에 맞는 낱말이 없으면 null이다. 이름 안의 장식 이모지는 쓰지 않는다. */
export function suggestLabelEmoji(name: string): string | null {
  const normalized = name.normalize('NFC');
  return RULES.find(([pattern]) => pattern.test(normalized))?.[1] ?? null;
}
